// Writes brands.js from Iconify's open logo sets: `npm install && npm run brands` in apps/kit.
// Add a brand by adding a line below. Mono marks follow the text color so they work in dark mode.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const sets = {
  logos: require('@iconify-json/logos/icons.json'),
  si: require('@iconify-json/simple-icons/icons.json'),
  vs: require('@iconify-json/vscode-icons/icons.json')
};

const brands = {
  Salesforce: 'logos:salesforce',
  Notion: 'si:notion',
  Shopify: 'logos:shopify',
  Microsoft: 'logos:microsoft-icon',
  'Microsoft Entra': 'logos:microsoft-icon',
  'Google Workspace': 'logos:google-icon',
  Google: 'logos:google-icon',
  Slack: 'logos:slack-icon',
  HubSpot: ['si:hubspot', '#FF7A59'],
  Stripe: ['si:stripe', '#635BFF'],
  QuickBooks: ['si:quickbooks', '#2CA01C'],
  Xero: 'logos:xero',
  Zendesk: 'si:zendesk',
  Intercom: 'logos:intercom-icon',
  Jira: 'logos:jira',
  Confluence: 'logos:confluence',
  GitHub: 'si:github',
  Linear: 'logos:linear-icon',
  Asana: 'logos:asana-icon',
  'monday.com': 'logos:monday-icon',
  Gmail: 'logos:google-gmail',
  'Microsoft Teams': 'logos:microsoft-teams',
  OneDrive: 'logos:microsoft-onedrive',
  Outlook: 'vs:file-type-outlook',
  'Google Drive': 'logos:google-drive',
  'Google Calendar': 'logos:google-calendar',
  'Google Sheets': ['si:googlesheets', '#34A853'],
  Dropbox: 'logos:dropbox',
  Box: 'logos:box',
  iCloud: ['si:icloud', '#3693F3'],
  Okta: 'si:okta',
  Airtable: 'logos:airtable',
  Snowflake: 'logos:snowflake-icon',
  Databricks: 'logos:databricks-icon',
  Zoom: 'logos:zoom-icon',
  Mailchimp: 'logos:mailchimp-icon',
  Trello: 'logos:trello',
  Figma: 'logos:figma',
  Zapier: 'logos:zapier-icon'
};

const out = {};
for (const [name, spec] of Object.entries(brands)) {
  const [ref, color] = Array.isArray(spec) ? spec : [spec];
  const [prefix, id] = ref.split(':');
  const set = sets[prefix];
  const icon = set.icons[id];
  if (!icon) throw new Error(`${ref} is not in @iconify-json/${prefix}`);
  const w = icon.width ?? set.width ?? 16;
  const h = icon.height ?? set.height ?? 16;
  const body = color ? icon.body.replaceAll('currentColor', color) : icon.body;
  out[name] = [`${icon.left ?? 0} ${icon.top ?? 0} ${w} ${h}`, body];
}

const header = '// Generated by brands.mjs from @iconify-json/logos, simple-icons and vscode-icons. Do not edit by hand.\n';
writeFileSync(new URL('./brands.js', import.meta.url), `${header}export const BRANDS = ${JSON.stringify(out, null, 2)};\n`);
console.log(`brands.js: ${Object.keys(out).length} logos`);
